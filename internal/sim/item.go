package sim

// Item — предмет мира: еда, оружие или труп.
//
// Местоположение предмета задается парой полей с инвариантом: если Holder
// равен нулю, предмет лежит на земле в Pos; иначе он в инвентаре существа
// Holder, а Pos фиктивен. Отдельное поле Holder (вместо «выпавшего предмета
// с позицией в инвентаре») нужно, чтобы выпадение инвентаря при смерти было
// переносом одного поля, а не пересозданием предмета с новым ID.
//
// Трупы — предметы наравне с едой: их можно съесть, а свидетели запомнят,
// кто именно ел. Поэтому Item хранит Owner — ID погибшего: без него
// воспоминание «он ел Гриблика» потеряло бы имя жертвы.
type Item struct {
	ID       ItemID
	Kind     ItemKind
	Holder   EntityID // 0 — на земле, иначе в инвентаре
	Pos      Vec2     // валидно, только когда предмет на земле
	Owner    EntityID // для трупа: кто погиб
	Consumed bool     // съеден: в мире для памяти и журнала, не для карты
}
