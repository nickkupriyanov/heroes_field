// Пакет sim — чистая пошаговая симуляция мира «После героя».
//
// Пакет не имеет внешних зависимостей (только стандартная библиотека) и не
// знает ни о графике, ни о вводе, ни о системном времени: одно и то же
// состояние можно воспроизвести в окне Ebitengine и в headless-прогоне.
// Порядок всех решений детерминирован: единственный источник случайности —
// генератор, созданный из seed в genesis-событии.
package sim

// Идентификаторы сущностей мира.
//
// Все ID выдаются при создании сущности, начинаются с 1 и никогда не
// переиспользуются: события хранят ID участников, поэтому переиспользование
// исказило бы историю (например, труп погибшего гоблина должен ссылаться
// именно на него, а не на нового жильца). Нулевое значение любого ID в событии
// означает «участника нет» — это позволяет опускать пустые поля при сериализации.
type (
	EntityID uint16 // существо
	ItemID   uint16 // предмет, включая трупы
	Seq      uint64 // сквозной номер события, монотонный по всему потоку
)

// Vec2 — координата клетки на карте, отсчёт с нуля: X — столбец, Y — строка.
// Используется и как позиция, и как смещение (например, шаг движения).
type Vec2 struct {
	X int
	Y int
}

// Add возвращает клетку, смещённую на d относительно v. Метод чистый: удобно
// вычислять цель шага или атаки, не мутируя исходную позицию.
func (v Vec2) Add(d Vec2) Vec2 {
	return Vec2{X: v.X + d.X, Y: v.Y + d.Y}
}

// Manhattan возвращает манхэттенское расстояние между клетками —
// метрика для AI-оценок (цена шага до еды или врага).
func (v Vec2) Manhattan(o Vec2) int {
	dx := v.X - o.X
	dy := v.Y - o.Y
	if dx < 0 {
		dx = -dx
	}
	if dy < 0 {
		dy = -dy
	}
	return dx + dy
}
